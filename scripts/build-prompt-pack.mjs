#!/usr/bin/env node
/**
 * Builds a ready-to-run generation brief for every pending image slot.
 *
 *   npm run images:prompts
 *
 * Pairs each unfilled path in the asset registry with the master prompt the
 * supplied pack wrote for it, the exact output dimensions from the image spec,
 * and the alt text the site already uses. The result is a single file that can
 * be worked through top to bottom in any image generator.
 *
 * Slots are ordered by how much they affect a buyer's first impression, not
 * alphabetically — the hero and the product front views are worth generating
 * before the warehouse shots.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const SPEC = {
  hero: "1920x1080", modelPortrait: "1200x1600", industry: "1600x900",
  fabricMacro: "1200x1200", technicalDetail: "1400x933", productSquare: "1600x1600",
};
function roleFor(p) {
  if (p.includes("/hero/")) return "hero";
  if (p.includes("/industries/")) return "modelPortrait";
  if (p.includes("/factory/") || p.includes("/export/") || p.includes("/development/")) return "industry";
  if (p.includes("/fabrics/") || p.includes("fabric-macro")) return "fabricMacro";
  if (p.includes("-detail")) return "technicalDetail";
  return "productSquare";
}

/** Buyer impact, highest first. */
const PRIORITY = ["/hero/", "/products/", "/industries/", "/factory/", "/development/", "/export/", "/case-studies/", "/fabrics/"];
const rank = (p) => { const i = PRIORITY.findIndex((s) => p.includes(s)); return i === -1 ? 99 : i; };

/* Registry: declared paths and their alt text. */
const registry = fs.readFileSync(path.join(root, "data", "assets.ts"), "utf8");
const declared = [];
for (const m of registry.matchAll(/"([\w.]+)":\s*\{\s*src:\s*"(\/assets\/[^"]+)",(?:\s*fallbackSrc:[^,]+,)?\s*alt:\s*"([^"]*)"/g)) {
  declared.push({ key: m[1], src: m[2], alt: m[3] });
}

/* Manifest: what already exists. */
const manifestSrc = fs.readFileSync(path.join(root, "data", "asset-manifest.ts"), "utf8");
const marker = "assetManifest: Record<string, ManifestEntry> = ";
const manifest = JSON.parse(manifestSrc.slice(manifestSrc.indexOf(marker) + marker.length, manifestSrc.lastIndexOf("}") + 1));

/* Supplied master prompts, keyed by their target path. */
const promptDir = path.join(root, "asset-pack", "prompts");
const prompts = new Map();
if (fs.existsSync(promptDir)) {
  for (const file of fs.readdirSync(promptDir)) {
    if (!file.endsWith(".prompt.txt")) continue;
    const body = fs.readFileSync(path.join(promptDir, file), "utf8").trim();
    // Filename encodes the target: category__[sub__]name.prompt.txt
    const stem = file.replace(/\.prompt\.txt$/, "");
    const parts = stem.split("__");
    const name = parts.pop();
    // Extension follows the category convention used by the pack.
    const ext = parts[0] === "brand" ? (name === "favicon" ? "png" : "svg") : name.includes("video") ? "webm" : "webp";
    const target = `/assets/${parts.join("/")}/${name}.${ext}`;
    if (body) prompts.set(target, body);
  }
}

const pending = declared
  .filter((d) => !manifest[d.src])
  .sort((a, b) => rank(a.src) - rank(b.src) || a.src.localeCompare(b.src));

const SHARED = `Premium editorial industrial apparel photography for AHM International, an apparel manufacturing and export company in Karachi, Pakistan. Authentic modern garment-production environment, real Pakistani workers where people appear, sophisticated natural lighting, subtle cinematic contrast, highly detailed fabric texture, realistic industrial equipment, contemporary global sourcing-company aesthetic. Photorealistic, extremely detailed, consistent colour grade across the whole set.

NEGATIVE (exclude from every image): any logo, brand mark, wordmark or readable signage; any text or lettering; staged corporate handshakes; stock-photo posing; futuristic or sci-fi machinery; distorted hands or anatomy; watermarks; identifiable company branding on garments, walls, cartons or equipment.`;

let out = `# Image generation pack

**Generated by \`npm run images:prompts\`.**

${pending.length} slots are still awaiting imagery. Each entry below gives the
exact output path, the size to render at, and the prompt.

## How to use this

1. Generate the image using the prompt for that slot.
2. Export it at the stated size to the stated path under \`public/assets/\`.
3. Run \`npm run assets\` to index it and generate its blur placeholder.
4. Run \`npm run images:audit\` to confirm it is within budget.

No layout or code change is needed — the slot already reserves the right shape,
and the designed specimen it replaces occupies the identical aspect ratio.

## Rules that apply to every image

${SHARED}

**Why no logos:** the site must never imply that an organisation shown is an AHM
customer, and readable branding in a generated image is both a legal risk and a
false claim. Garments, cartons and walls stay unbranded.

---

`;

let currentGroup = "";
for (const item of pending) {
  const group = item.src.split("/")[2];
  if (group !== currentGroup) {
    currentGroup = group;
    out += `\n## ${group}\n`;
  }
  const role = roleFor(item.src);
  const supplied = prompts.get(item.src);
  out += `
### \`${item.src}\`

- **Render at:** ${SPEC[role]}
- **Registry key:** \`${item.key}\`
- **Alt text already written:** ${item.alt}

\`\`\`
${supplied ?? `${SHARED}\n\n${item.alt}.`}
\`\`\`
`;
}

fs.writeFileSync(path.join(root, "IMAGE-PROMPTS.md"), out);
console.log(`IMAGE-PROMPTS.md written — ${pending.length} slots, ${prompts.size} supplied prompts matched`);
